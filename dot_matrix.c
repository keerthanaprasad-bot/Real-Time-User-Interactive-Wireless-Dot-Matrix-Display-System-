void editdate()
{

	int d,dt,m,y,max_days;

 	while(1)
 	{
		INPUT:
//		index_val=0;
//		U0THR = str3[tx_index++];
		UART0_Str(str3);
		buffer=(char *)rec_buff;
		index_val=0;
		while(r_flag!=1);
	//	index_val=0;
		r_flag=0;
		f=0;
		if(sscanf(buffer,"%d %d/%d/%d",&d,&dt,&m,&y)!=4)
		{
//				index_val=0;
//				U0THR = format[tx_index++];	
				UART0_Str(format);
				goto INPUT;		
		}
		if(!(d>=1 && d<=7))
		{
//				index_val=0;
//				U0THR = day_str[tx_index++];
				UART0_Str(day_str);	
				goto INPUT;	
		}
		if(!(m>=1 && m<=12))
		{
//				tx_index=0;
//				U0THR = month_str[tx_index++];
				UART0_Str(month_str);	
				goto INPUT;		
		}
		if(m==2)
		{
			if((y%4==0 && y%100!=0)||(y%400==0))
			{
				max_days=29;
			}
			else
			{
				max_days=28;
			}
		}
		else if(m==4 || m==6  || m==9 || m==11)
		{
			max_days=30;
		}
		else 
		{
			max_days=31;
		}
		if(!(dt>=1 && dt<=max_days))
		{
//				tx_index=0;
//				U0THR = date_str[tx_index++];
				UART0_Str(date_str);		
				goto INPUT;	
		}
		if(!(y>=0 && y<=2030))
		{
				//tx_index=0;
			//	U0THR = year_str[tx_index++];
				UART0_Str(year_str);	
				goto INPUT;		
		}
		SetRTCDateInfo(dt,m,y);
	  	SetRTCDay(d);
		break;
	}
}
